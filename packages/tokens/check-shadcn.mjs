/**
 * THE TAILWIND v4 THEME COMPILES IN A STOCK TAILWIND (#2997 gate 5) — `npm run -w @prism3/tokens check:shadcn`.
 *
 * The engine's `emit-tailwind.ts` writes `tailwind/<brand>.theme.css`: the shadcn variables in `:root` and `.dark`
 * and an `@theme inline` block. This gate is the consumer's side. A fixture that uses one utility per family the theme
 * promises is compiled against each brand's file by the stock Tailwind CLI (`@tailwindcss/cli`, pinned exact in this
 * package), with no plugin and no config, and every utility must come out resolved to the brand's own value.
 *
 * INDEPENDENCE (docs/34). Nothing here imports the engine. The theme files are generated by running the engine's
 * emitter as a process into a temp dir (it is not a committed artifact until #2997 PR 4). The utilities and what each
 * must read are typed below, from the proposal's fixture (#2997 §8 gate 5), never from the map. A dimension's expected
 * value is read from `<brand>.tokens.json` with this file's own alias walk; Tailwind's `calc()` is evaluated here.
 *
 *   [PIN]         the installed Tailwind is the version `package.json` pins.
 *   [UTILITY]     each fixture utility compiled to a rule; a missing one fails `<utility> utility unresolved`.
 *   [READS]       a color or shadow utility reads `var(--<name>)`, and the compiled CSS sets `--<name>` in both
 *                 `:root` and `.dark`, so the mode switch reaches it; a dimension or font utility computes to the
 *                 brand's DTCG value.
 *
 * MUTATION: drop `--color-ring` from the emitter's `@theme` and this fails `outline-ring utility unresolved` by name.
 */
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..');
const engineOut = join(repo, 'packages/engine/out');
const require = createRequire(import.meta.url);

/** [utility, CSS property, what it must read]. Typed from #2997 §8 gate 5. */
const FIXTURE = [
  ['bg-primary', 'background-color', { var: 'primary' }],
  ['text-muted-foreground', 'color', { var: 'muted-foreground' }],
  ['outline-ring', 'outline-color', { var: 'ring' }],
  ['shadow-md', '--tw-shadow', { var: 'pds3-shadow-md' }],
  ['rounded-lg', 'border-radius', { role: 'radius.lg' }],
  ['p-2', 'padding', { role: 'space.100' }],
  ['font-sans', 'font-family', { font: 'core.font.family.body' }],
];

const failures = [];
const fail = (m) => failures.push(m);

// [PIN]
const pinned = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8')).devDependencies;
for (const name of ['tailwindcss', '@tailwindcss/cli']) {
  const got = JSON.parse(readFileSync(require.resolve(`${name}/package.json`), 'utf8')).version;
  if (got !== pinned[name]) fail(`[PIN] ${name} ${got} installed, ${pinned[name]} pinned`);
}

const tmp = mkdtempSync(join(tmpdir(), 'prism3-tailwind-'));
process.on('exit', () => rmSync(tmp, { recursive: true, force: true }));
const gen = spawnSync('npx', ['tsx', 'packages/engine/emit-tailwind.ts', '--out', tmp], { cwd: repo, encoding: 'utf8' });
if (gen.status !== 0) { console.error(`✗ emit-tailwind.ts --out exited ${gen.status}: ${(gen.stderr || gen.stdout).trim()}`); process.exit(1); }

/** A role's `$value` in the brand's full tree, aliases followed. */
const roleValue = (tree, root, role) => {
  const at = (p) => p.split('.').reduce((n, k) => (n && typeof n === 'object' ? n[k] : undefined), tree);
  let v = at(role)?.$value;
  for (let hop = 0; hop < 16 && typeof v === 'string' && /^\{.+\}$/.test(v); hop++) {
    const p = v.slice(1, -1);
    v = at(p.startsWith(`${root}.`) ? p.slice(root.length + 1) : p)?.$value;
  }
  return v;
};

/** The body of the first rule whose selector is exactly `sel`, or undefined. */
const ruleBody = (css, sel) => {
  const re = new RegExp(`(^|[\\s}])${sel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\{([^}]*)\\}`, 'm');
  return re.exec(css)?.[2];
};
const decl = (body, prop) => new RegExp(`(?:^|[;{\\s])${prop.replace(/[-]/g, '\\-')}\\s*:\\s*([^;]+);`).exec(body ?? '')?.[1]?.trim();
/** `calc(<n>px * <k>)` or a plain `<n>px`, in px. */
const px = (v) => {
  const c = /^calc\(\s*([\d.]+)px\s*\*\s*([\d.]+)\s*\)$/.exec(v ?? '');
  if (c) return Number(c[1]) * Number(c[2]);
  const p = /^([\d.]+)px$/.exec(v ?? '');
  return p ? Number(p[1]) : NaN;
};

const cli = require.resolve('@tailwindcss/cli/package.json').replace(/package\.json$/, '');
const twIndex = require.resolve('tailwindcss/index.css');
const files = readdirSync(join(tmp, 'tailwind')).filter((f) => f.endsWith('.theme.css')).sort();
if (!files.length) fail('[UTILITY] the emitter wrote no theme file');
let held = 0;
for (const f of files) {
  const brand = f.slice(0, -'.theme.css'.length);
  const input = join(tmp, `${brand}.in.css`), output = join(tmp, `${brand}.out.css`);
  writeFileSync(input, `@import "${twIndex}" source(none);\n@import "${join(tmp, 'tailwind', f)}";\n@source inline("${FIXTURE.map(([u]) => u).join(' ')}");\n`);
  const bin = JSON.parse(readFileSync(join(cli, 'package.json'), 'utf8')).bin;
  const r = spawnSync(process.execPath, [join(cli, typeof bin === 'string' ? bin : bin.tailwindcss), '-i', input, '-o', output], { cwd: here, encoding: 'utf8' });
  if (r.status !== 0) { fail(`${brand}: the Tailwind CLI exited ${r.status}: ${(r.stderr || '').trim().split('\n').slice(-2).join(' / ')}`); continue; }
  const css = readFileSync(output, 'utf8');
  const full = JSON.parse(readFileSync(join(engineOut, `${brand}.tokens.json`), 'utf8'));
  const root = Object.keys(full)[0];
  for (const [util, prop, want] of FIXTURE) {
    const got = decl(ruleBody(css, `.${util.replace(/[.]/g, '\\.')}`), prop);
    if (got === undefined) { fail(`${brand}: ${util} utility unresolved (no ${prop} in a .${util} rule)`); continue; }
    if (want.var) {
      if (got !== `var(--${want.var})`) { fail(`${brand}: ${util} reads ${got}, not var(--${want.var})`); continue; }
      for (const sel of [':root', '.dark']) if (!decl(ruleBody(css, sel), `--${want.var}`)) fail(`${brand}: ${util} — --${want.var} is not set in ${sel}`);
    } else if (want.role) {
      const exp = px(roleValue(full[root], root, want.role));
      if (!(px(got) === exp)) fail(`${brand}: ${util} computes ${got}, not ${want.role} (${exp}px)`);
    } else if (want.font) {
      const face = roleValue(full[root], root, want.font);
      if (!got.includes(String(face))) fail(`${brand}: ${util} is ${got}, not ${want.font} (${face})`);
    }
    held++;
  }
}

if (failures.length) {
  console.error(`✗ check:shadcn — ${failures.length} failure(s)`);
  for (const f of failures) console.error(`    ${f}`);
  process.exit(1);
}
console.log(`✓ check:shadcn — ${files.length} brand themes compiled by stock Tailwind ${pinned.tailwindcss}; ${held} utilities ` +
  `(${FIXTURE.length} each) resolved to the brand's own value, every color and shadow set in :root and .dark.`);
