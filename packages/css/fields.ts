/**
 * THE FIELD GENERATORS (#3408 S3, owner decisions Q96 A and Q100 A): `field-label.css`, `field-message.css`,
 * `text-field.css` and `password-field.css`, from the engine's emission. `generate.ts` calls these and writes the files.
 *
 * WHAT IT READS, and why each source (the same split as the button, `generate.ts`):
 *   - `specs.json` — every color per part, status and state; every padding, gap, height, minimum width and icon size per
 *     size; every text style. Nothing here restates a token a row names.
 *   - `component-defs.json` — each def's code props and their defaults, so `data-prop-*` defaults and the axis → prop
 *     mapping (`status` is the `validation` prop) come from the def.
 *   - Since Q142 A (#3506, #3839) the box's radius and its border width per state (the 2px focus edge, #3399) are
 *     redlines, the shared ring's style is in every host's `focusRing` row, and the spinner's motion tokens are its
 *     `motion` bindings. The pending spinner takes the leading glyph's size and ink, read from that glyph's own rows.
 *   - `residual.ts`, for the one fact here the emission does not carry yet: the nested Show/Hide button's hit floor
 *     (the button def's `size.<size>.hit-target`, Q-HT1 A).
 *
 * THE MARKUP CONTRACT is in this package's README; `check-parity-fields.ts` holds its own copy (docs/34). States come
 * from native and ARIA state on the one `<input>`: `:disabled`, `[readonly]`, `:focus-visible`, `[aria-busy]`, and
 * the box's `:hover`. Statuses come from `data-prop-validation`; the contract also asks for `aria-invalid="true"` at
 * error. The nested label and message FOLLOW the field (the emission's `nesting.follows`): the field's size sizes the
 * label, the field's status sets the message, so an author sets each once, on the field.
 */
import { motionBinding, readUncommitted, ringStyle, uniformRedline } from './emission';
import { hitTargetFloor } from './residual';
import { fmt, kebab, typeDecls, v, type Rule } from './tokens';

const PREFIX = 'p3';
const specs = readUncommitted('specs.json').components;
const defs = readUncommitted('component-defs.json').components;

/** One component's `data-prop-*` selector builder, from its def's props: the default also matches an absent attribute. */
const propsOf = (id: string) => {
  const def = defs[id]?.def;
  if (!def) throw new Error(`no "${id}" in component-defs.json`);
  const prop = (name: string) => {
    const p = def.props.find((x: any) => x.name === name);
    if (!p) throw new Error(`${id} has no prop "${name}"`);
    return p;
  };
  /** A spec axis's prop: the prop of that name, else the one enum prop whose values are the axis's (`status` → `validation`). */
  const axisProp = (axis: string, values: string[]): string => {
    if (def.props.some((x: any) => x.name === axis)) return axis;
    const same = def.props.filter((x: any) => Array.isArray(x.values) && [...x.values].sort().join() === [...values].sort().join());
    if (same.length !== 1) throw new Error(`${id}: axis "${axis}" matches ${same.length} props by its values`);
    return same[0].name;
  };
  const sel = (name: string, value: string): string => {
    const a = `data-prop-${name.toLowerCase()}`;
    return value === String(prop(name).default) ? `:is(:not([${a}]), [${a}="${value}"])` : `[${a}="${value}"]`;
  };
  return { def, prop, axisProp, sel };
};

const valueOf = (val: any, where: string): string => {
  if (val.token) return v(val.token);
  throw new Error(`${where}: a value with no token: ${JSON.stringify(val)}`);
};

/** Paint keys → CSS properties. `caret` paints the native caret (codeOnly `platform-owned`: the focus caret). */
const PAINT: Record<string, string> = { fill: 'background-color', stroke: 'border-color', ink: 'color', icon: 'color' };

/** The spinner's motion, by binding key (#3839): the spinner every field shows while pending. */
const motionOf = () => (key: string) => v(motionBinding(specs.spinner, key));

const write = (title: string, src: string, rules: Rule[], reduced: Rule[] = [], keyframes = false): string => [
  `/* @prism3/css — ${title}. GENERATED by packages/css/generate.ts from the engine's emission`,
  ` * (${src}) — do not edit; change the def and regenerate.`,
  ` * Needs the token CSS from @prism3/tokens. Markup contract: packages/css/README.md. */`,
  `@layer ${PREFIX} {`,
  rules.map((r) => fmt(r, '  ')).join('\n'),
  ...(reduced.length ? [`  @media (prefers-reduced-motion: reduce) {`, reduced.map((r) => fmt(r, '    ')).join('\n'), `  }`] : []),
  ...(keyframes ? [`  @keyframes ${PREFIX}-spin {\n    to { transform: rotate(1turn); }\n  }`, `  @keyframes ${PREFIX}-fade-in {\n    from { opacity: 0; }\n  }`] : []),
  `}`,
  '',
].join('\n');

// ================================================================================================ field-label
const LABEL = `.${PREFIX}-field-label`;
const labelPart = (part: string) => `${LABEL}__${kebab(part.split('/').pop()!)}`;

/**
 * The label's rules under a prefix. Standalone, the prefix is the label itself and its size is its own prop; nested, the
 * prefix is the host's path to it and `size` is the host's (the emission's `follows: ["size"]`).
 */
const labelRules = (scope: (where: Record<string, string>) => string, keys: string[]): Rule[] => {
  const spec = specs['field-label'];
  const out: Rule[] = [];
  for (const row of spec.type) for (const p of row.parts) out.push({ sel: `${scope(pick(row.where, keys))} > ${labelPart(p.part)}`, decls: typeDecls(p.textStyle) });
  return out;
};
const pick = (o: Record<string, string>, keys: string[]) => Object.fromEntries(Object.entries(o).filter(([k]) => keys.includes(k)));

export const fieldLabelCss = (): { css: string; rules: number } => {
  const spec = specs['field-label'];
  const P = propsOf('field-label');
  const own = (where: Record<string, string>) => LABEL + Object.entries(where).map(([k, x]) => P.sel(P.axisProp(k, axisValues(spec, k)), x)).join('');
  const rules: Rule[] = [
    { sel: LABEL, decls: [['box-sizing', 'border-box'], ['display', 'flex'], ['align-items', 'baseline'], ['margin', '0']], note: 'the visible, persistent name of a field: a native <label for>' },
    { sel: `${LABEL} > ${labelPart('container/indicator')}`, decls: [['display', 'none']], note: 'the required marker: shown by the label\'s own `required`, or by the field\'s required input' },
    { sel: `${LABEL}${P.sel('required', 'true')} > ${labelPart('container/indicator')}`, decls: [['display', 'inline']] },
  ];
  for (const row of spec.redlines) for (const p of row.parts) for (const [k, val] of Object.entries<any>(p.values)) {
    if (val.source === 'literal' && (k === 'buildWidth' || k === 'maxWidth')) continue; // the Figma build width; in code the label takes its container's
    if (p.part === 'container' && k === 'gap') rules.push({ sel: own(pick(row.where, ['size'])), decls: [['column-gap', valueOf(val, `field-label ${k}`)]] });
    else throw new Error(`field-label: no CSS for redline ${p.part}.${k}`);
  }
  rules.push(...labelRules(own, ['size', 'weight']));
  // Color: rest only. `disabled` has no prop on the label; it comes from the field it names (the host's rules).
  for (const row of spec.colors) {
    if (row.where.state !== 'rest') continue;
    for (const p of row.parts) rules.push({ sel: `${own(pick(row.where, ['emphasis', 'weight']))} > ${labelPart(p.part)}`, decls: [[PAINT[k1(p)], v(p[k1(p)])]] });
  }
  return { css: write('FieldLabel (field-label)', 'specs.json, component-defs.json', rules), rules: rules.length };
};
const k1 = (p: any) => { const ks = Object.keys(p).filter((k) => k !== 'part'); if (ks.length !== 1) throw new Error(`${p.part}: ${ks.length} paints`); return ks[0]; };
const axisValues = (spec: any, axis: string): string[] => spec.axes.find((a: any) => a.name === axis).values;

// ================================================================================================ field-message
const MSG = `.${PREFIX}-field-message`;
const msgPart = (part: string) => `${MSG}__${kebab(part.split('/').pop()!)}`;
/** A message part's selector chain under the message root (`message/glyphCell/errorGlyph` → `> __glyph-cell > __error-glyph`). */
const msgChain = (part: string) => part.split('/').slice(1).map((_, i, a) => msgPart(a.slice(0, i + 1).join('/'))).join(' > ');

/** The message's status-dependent rules: colors, and which glyph shows (the anatomy's `when.status`). */
const messageStatusRules = (scope: (status: string) => string): Rule[] => {
  const spec = specs['field-message'];
  const out: Rule[] = [];
  for (const a of spec.anatomy) {
    const when = a.when?.status as string[] | undefined;
    if (!when) continue;
    out.push({ sel: `${scope('*')} > ${msgChain(a.part)}`, decls: [['display', 'none']] });
    for (const s of when) out.push({ sel: `${scope(s)} > ${msgChain(a.part)}`, decls: [['display', 'inline-flex']] });
  }
  for (const row of spec.colors) for (const p of row.parts) out.push({ sel: `${scope(row.where.status)} > ${msgChain(p.part)}`, decls: [[PAINT[k1(p)], v(p[k1(p)])]] });
  return out;
};

/** `max(0, A − B) ÷ 2` as the redline's computed rule states it, with "one label line" the caption's `1lh`. */
const computedPad = (rule: string): string => {
  let m = rule.match(/^max\(0, (\S+) − one label line\) ÷ 2$/);
  if (m) return `max(0px, calc((${v(m[1])} - 1lh) / 2))`;
  m = rule.match(/^max\(0, one label line − (\S+)\) ÷ 2$/);
  if (m) return `max(0px, calc((1lh - ${v(m[1])}) / 2))`;
  throw new Error(`field-message: no CSS for the computed rule "${rule}"`);
};

export const fieldMessageCss = (): { css: string; rules: number } => {
  const spec = specs['field-message'];
  const P = propsOf('field-message');
  const status = (s: string) => (s === '*' ? MSG : `${MSG}${P.sel(P.axisProp('status', axisValues(spec, 'status')), s)}`);
  const rules: Rule[] = [
    { sel: MSG, decls: [['box-sizing', 'border-box'], ['display', 'flex'], ['align-items', 'flex-start'], ['margin', '0']], note: 'a helper or validation message; the field\'s input names it in aria-describedby' },
    { sel: `${MSG} > ${msgChain('message/glyphCell')}`, decls: [['flex', 'none']] },
    { sel: `${MSG} > ${msgChain('message/glyphCell')} svg`, decls: [['inline-size', '100%'], ['block-size', '100%']] },
  ];
  for (const row of spec.type) for (const p of row.parts) {
    // On the message too, so both cells' `1lh` is the caption's line (the first-line padding below reads it).
    rules.push({ sel: MSG, decls: typeDecls(p.textStyle), note: 'the caption\'s type, on the message, so each cell\'s 1lh is one caption line' });
    rules.push({ sel: `${MSG} > ${msgChain(p.part)}`, decls: typeDecls(p.textStyle) });
  }
  for (const row of spec.redlines) for (const p of row.parts) {
    const decls: [string, string][] = [];
    for (const [k, val] of Object.entries<any>(p.values)) {
      if (val.source === 'literal' && k === 'buildWidth') continue;
      if (val.source === 'computed') { if (k !== 'paddingTop') throw new Error(`field-message: computed ${k}`); decls.push(['padding-block-start', computedPad(val.rule)]); continue; }
      const prop = ({ gap: 'column-gap', minHeight: 'min-block-size', height: 'block-size', width: 'inline-size' } as Record<string, string>)[k];
      if (!prop) throw new Error(`field-message: no CSS for redline ${p.part}.${k}`);
      decls.push([prop, valueOf(val, `${p.part}.${k}`)]);
    }
    rules.push({ sel: p.part === 'message' ? MSG : `${MSG} > ${msgChain(p.part)}`, decls, note: p.part === 'message/captionCell' ? 'the first line (#3360, Q-FM1 A): the shorter cell pads down by half the difference, so the glyph centers on the caption\'s first line' : undefined });
  }
  rules.push(...messageStatusRules(status));
  return { css: write('FieldMessage (field-message)', 'specs.json, component-defs.json', rules), rules: rules.length };
};

// ================================================================================================ the fields
/**
 * The field's state model on the one `<input>` (the entry). The design states fold to five code states, because
 * `filled` / `focus-visible-filled` differ from `rest` / `focus-visible` only in which text shows, the value or the
 * placeholder, and the code paints both at once (`color` and `::placeholder`): codeOnly `empty`.
 */
const CODE_STATE: Record<string, string> = {
  rest: 'rest', filled: 'rest', hover: 'hover', 'focus-visible': 'focus', 'focus-visible-filled': 'focus', disabled: 'disabled', 'read-only': 'read-only',
};
const CODE_ORDER = ['rest', 'hover', 'read-only', 'focus', 'disabled'];

const fieldCss = (id: 'text-field' | 'password-field'): { css: string; rules: number } => {
  const spec = specs[id];
  const P = propsOf(id);
  const ROOT = `.${PREFIX}-${id}`;
  const cls = (seg: string) => `${ROOT}__${kebab(seg)}`;
  // The box's corner and stroke (#3839): one radius; one stroke width in every code state but focus, whose edge is
  // its own (#3399). The CSS writes each once, so a binding that moves between rows it folds together fails here.
  const BOX = 'container/control';
  const isFocus = (w: Record<string, string>) => CODE_STATE[w.state] === 'focus';
  const boxRadius = uniformRedline(spec, BOX, 'radius');
  const boxStroke = uniformRedline(spec, BOX, 'strokeWidth', (w) => !isFocus(w));
  const edge = uniformRedline(spec, BOX, 'strokeWidth', isFocus);
  // The pending spinner (codeOnly): the def binds no spinner row, so it takes the leading glyph's size and ink at rest.
  const GLYPH = 'container/control/content/leadingVisual';
  const glyphSize = uniformRedline(spec, GLYPH, 'width');
  if (uniformRedline(spec, GLYPH, 'height') !== glyphSize) throw new Error(`${id}: the leading glyph is not square`);
  const glyphInk = spec.colors.find((r: any) => r.where.state === 'rest' && r.where.status === P.prop(P.axisProp('status', axisValues(spec, 'status'))).default)
    ?.parts.find((p: any) => p.part === GLYPH)?.icon;
  if (!glyphInk) throw new Error(`${id}: no rest ink for ${GLYPH}`);
  const E = cls('entry');
  const statusProp = P.axisProp('status', axisValues(spec, 'status'));
  const nest = (part: string) => spec.nesting.find((n: any) => n.part === part);

  // ---------------------------------------------------------------- parts → selectors
  /** The nested instances, by the emission's `nesting`: their root class, not a part class. */
  const nestedClass = (part: string): string | undefined => {
    const n = nest(part);
    if (!n || n.kind !== 'instance') return undefined;
    if (n.component === 'field-label') return LABEL;
    if (n.component === 'field-message') return MSG;
    if (n.component === 'button') return `.${PREFIX}-button${cls(part.split('/').pop()!)}`;
    throw new Error(`${id}: no class for nested ${n.component} at ${part}`);
  };
  const STATE_ROOT: Record<string, string> = {
    rest: '',
    hover: `:not(:has(${E}:disabled, ${E}:read-only, ${E}:focus-visible))`,
    'read-only': `:has(${E}:read-only:not(:disabled)):not(:has(${E}:focus-visible))`,
    focus: `:has(${E}:focus-visible)`,
    disabled: `:has(${E}:disabled)`,
  };
  /** `container/control/content/entry/placeholder` → `ROOT… > __control > __content > __entry::placeholder`. */
  const partSel = (root: string, part: string, state = 'rest'): string => {
    const segs = part.split('/').slice(1);
    let s = root;
    for (let i = 0; i < segs.length; i++) {
      const path = ['container', ...segs.slice(0, i + 1)].join('/');
      const seg = segs[i];
      if (seg === 'placeholder') { s += '::placeholder'; break; }
      if (seg === 'value' || seg === 'caret' || seg === 'caretEnd') break; // the input itself
      s += ` > ${nestedClass(path) ?? cls(seg)}`;
      if (seg === 'control' && state === 'hover') s += ':hover';
    }
    return s;
  };
  const rootSel = (where: Record<string, string>, state = 'rest') =>
    ROOT + Object.entries(where).filter(([k]) => k !== 'state').map(([k, x]) => P.sel(k === 'status' ? statusProp : k, x)).join('') + STATE_ROOT[state];

  const rules: Rule[] = [];
  const add = (sel: string, decls: [string, string][], note?: string) => { if (decls.length) rules.push({ sel, decls, note }); };
  // The nested Show/Hide button (password-field only), selected with the variant its nesting states, so its rules
  // outrank Button's own flush rules by specificity, never by stylesheet order.
  const toggleAt = spec.nesting.find((n: any) => n.component === 'button');
  const BP = propsOf('button');
  const tsel = (r: string) => `${partSel(r, toggleAt.part)}${['appearance', 'size', 'inset'].map((k) => BP.sel(k, toggleAt.variant[k])).join('')}`;

  // ---------------------------------------------------------------- the base
  const control = partSel(ROOT, 'container/control');
  const content = partSel(ROOT, 'container/control/content');
  add(ROOT, [['box-sizing', 'border-box'], ['display', 'flex'], ['flex-direction', 'column']], 'the field: label, box and message in one tree, so <label for> and aria-describedby reach the input');
  add(control, [
    ['box-sizing', 'border-box'], ['display', 'flex'], ['align-items', 'center'],
    ['border-style', 'solid'],
    ['border-width', v(boxStroke)],
    ['border-radius', v(boxRadius)],
  ], 'the box: the stroke is the field\'s boundary (1.4.11)');
  add(content, [['display', 'flex'], ['align-items', 'center'], ['flex', '1 1 auto'], ['min-inline-size', '0']]);
  add(partSel(ROOT, 'container/control/content/entry/value'), [
    ['flex', '1 1 auto'], ['min-inline-size', '0'], ['margin', '0'], ['padding', '0'], ['border', '0'],
    ['background-color', 'transparent'], ['outline', 'none'],
  ], 'the entry: one native <input>; its placeholder and its value are one element (codeOnly `empty`). The box draws its focus edge, so the input draws none');
  const visuals = spec.anatomy.filter((a: any) => a.kind === 'swap').map((a: any) => a.part);
  for (const part of visuals) {
    add(partSel(ROOT, part), [['display', 'inline-flex'], ['flex', 'none']]);
    add(`${partSel(ROOT, part)} > svg`, [['inline-size', '100%'], ['block-size', '100%']]);
  }

  // ---------------------------------------------------------------- sizes (redlines)
  const SIZE: Record<string, string> = {
    paddingTop: 'padding-block-start', paddingBottom: 'padding-block-end', paddingLeft: 'padding-inline-start', paddingRight: 'padding-inline-end',
    width: 'inline-size',
  };
  // The key grows by `state` where the stroke moves (#3839), but the CSS sizes by `size` alone (the stroke is the base
  // rule and the focus edge): rows that differ only by state collapse to one rule, and any other value that moves with
  // state fails here, by part, rather than being written once per state.
  const sized = new Map<string, string>();
  for (const row of spec.redlines) {
    const r = rootSel(row.where);
    for (const p of row.parts) {
      const leafName = p.part.split('/').pop();
      if (leafName === 'caret' || leafName === 'caretEnd') continue; // codeOnly platform-owned: the browser's native caret
      const decls: [string, string][] = [];
      for (const [k, val] of Object.entries<any>(p.values)) {
        if (p.part === BOX && (k === 'radius' || k === 'strokeWidth')) continue; // the base rule and the focus edge, asserted above
        if (k === 'buildWidth' && val.source === 'literal') continue; // the Figma build width; in code the field fills its container
        if (k === 'minWidth' && val.source === 'literal' && typeof val.px === 'number') { decls.push(['min-inline-size', `${val.px}px`]); continue; }
        if (k === 'gap') { decls.push([p.part === 'container' ? 'row-gap' : 'column-gap', valueOf(val, `${p.part}.gap`)]); continue; }
        if (k === 'height') { decls.push([p.part === 'container/control' ? 'min-block-size' : 'block-size', valueOf(val, `${p.part}.height`)]); continue; }
        if (!SIZE[k]) throw new Error(`${id}: no CSS for redline ${p.part}.${k}`);
        decls.push([SIZE[k], valueOf(val, `${p.part}.${k}`)]);
      }
      const sel = toggleAt && p.part === toggleAt.part ? tsel(r) : partSel(r, p.part);
      const had = sized.get(sel);
      if (had !== undefined) {
        if (had !== JSON.stringify(decls)) throw new Error(`${id}: ${p.part} sizes differently at ${JSON.stringify(row.where)} than in another state of the same size`);
        continue;
      }
      sized.set(sel, JSON.stringify(decls));
      add(sel, decls);
    }
  }

  // ---------------------------------------------------------------- text
  for (const row of spec.type) for (const p of row.parts) add(partSel(rootSel(row.where), p.part), typeDecls(p.textStyle));

  // ---------------------------------------------------------------- colors per status and state
  const merged = new Map<string, Map<string, { part: string; prop: string; token: string }>>();
  for (const row of spec.colors) {
    const cs = CODE_STATE[row.where.state];
    if (!cs) throw new Error(`${id}: no code state for "${row.where.state}"`);
    const key = `${row.where.status}|${cs}`;
    if (!merged.has(key)) merged.set(key, new Map());
    const m = merged.get(key)!;
    for (const p of row.parts) for (const [k, token] of Object.entries<any>(p)) {
      if (k === 'part') continue;
      const leafName = p.part.split('/').pop();
      const prop = leafName === 'caret' || leafName === 'caretEnd' ? 'caret-color' : PAINT[k];
      if (!prop) throw new Error(`${id}: no CSS for paint "${k}" on ${p.part}`);
      const at = `${partSel('', p.part)}|${prop}`;
      const had = m.get(at);
      if (had && had.token !== token) throw new Error(`${id} ${key}: ${p.part} ${prop} is ${had.token} in one design state and ${token} in another`);
      m.set(at, { part: p.part, prop, token });
    }
  }
  // Disabled with a value: the spec's disabled rows show the placeholder only. The def has one disabled entry-text ink
  // (`disabled.label.on-fill`), so the value takes the placeholder's disabled ink, read from the row.
  for (const status of axisValues(spec, 'status')) {
    const m = merged.get(`${status}|disabled`)!;
    const ph = [...m.values()].find((x) => x.part.endsWith('/placeholder'));
    if (!ph) throw new Error(`${id} ${status} disabled: no placeholder ink`);
    m.set(`value-ink`, { part: 'container/control/content/entry/value', prop: 'color', token: ph.token });
  }
  for (const cs of CODE_ORDER) for (const status of axisValues(spec, 'status')) {
    const m = merged.get(`${status}|${cs}`);
    if (!m) throw new Error(`${id}: no rows for ${status} ${cs}`);
    const byPart = new Map<string, [string, string][]>();
    for (const x of m.values()) {
      const s = partSel(rootSel({ status }, cs), x.part, cs);
      byPart.set(s, [...(byPart.get(s) ?? []), [x.prop, v(x.token)]]);
      // The focus edge (#3399): the stroke's own paint, drawn as an outline inside the box, so nothing moves.
      if (cs === 'focus' && x.part === 'container/control' && x.prop === 'border-color') byPart.get(s)!.push(['outline-color', v(x.token)]);
    }
    for (const [s, decls] of byPart) add(s, decls);
  }
  add(partSel(`${ROOT}${STATE_ROOT.focus}`, 'container/control'), [
    ['outline-width', v(edge)],
    ['outline-style', v(ringStyle(specs))],
    ['outline-offset', `calc(${v(edge)} * -1)`],
  ], `the focus edge (#3399): border-width.focus-visible, ${edge}, inside the box at its radius; an outline, so it survives forced colors`);

  // ---------------------------------------------------------------- the nested label and message
  const labelAt = spec.nesting.find((n: any) => n.component === 'field-label');
  const msgAt = spec.nesting.find((n: any) => n.component === 'field-message');
  if (!labelAt?.follows.includes('size') || labelAt.when?.state?.disabled?.state !== 'disabled') throw new Error(`${id}: the nested field-label no longer follows size and disabled`);
  if (!msgAt?.follows.includes('status')) throw new Error(`${id}: the nested field-message no longer follows status`);
  const labelSel = (r: string) => partSel(r, labelAt.part);
  const LP = propsOf('field-label');
  const lp = (where: Record<string, string>) => Object.entries(where).map(([k, x]) => LP.sel(k, x)).join('');
  // follows size: the field's size sizes its label
  rules.push(...labelRules((w) => `${labelSel(rootSel(pick(w, ['size'])))}${lp(pick(w, ['weight']))}`, ['size', 'weight'])
    .map((r, i) => ({ ...r, note: i === 0 ? 'the label follows the field\'s size (nesting `follows: ["size"]`)' : undefined })));
  // disabled: the field's disabled input disables its label's ink (nesting `when.state.disabled`)
  for (const row of specs['field-label'].colors) {
    if (row.where.state !== 'disabled') continue;
    for (const p of row.parts) add(`${labelSel(rootSel({}, 'disabled'))}${lp(pick(row.where, ['emphasis', 'weight']))} > ${labelPart(p.part)}`, [[PAINT[k1(p)], v(p[k1(p)])]]);
  }
  add(`${labelSel(`${ROOT}:has(${E}:required)`)} > ${labelPart('container/indicator')}`, [['display', 'inline']], 'the label\'s required marker follows the input\'s `required`');
  // follows status: the field's status sets its message
  const mr = messageStatusRules((s) => partSel(s === '*' ? ROOT : rootSel({ status: s }), msgAt.part));
  mr[0].note = 'the message follows the field\'s status (nesting `follows: ["status"]`)';
  rules.push(...mr);

  // ---------------------------------------------------------------- pending (codeOnly: a spinner replaces an adornment)
  const spin = `${control} > ${cls('spinner')}`;
  const busy = `${ROOT}:has(${E}[aria-busy="true"])`;
  const motion = motionOf();
  add(spin, [['display', 'none'], ['flex', 'none'], ['inline-size', v(glyphSize)], ['block-size', v(glyphSize)], ['color', v(glyphInk)]],
    'pending (codeOnly): the spinner takes the trailing cell at the glyph\'s size and ink; the def binds no spinner row, so its size and ink are the def\'s icon-size and icon keys');
  add(`${busy} > ${cls('control')} > ${cls('spinner')}`, [['display', 'inline-flex'], ['animation', `${PREFIX}-fade-in ${motion('motion.enter')} ${motion('motion.enter-easing')} both`]]);
  if (visuals.includes('container/control/trailingVisual')) add(`${busy} > ${cls('control')} > ${cls('trailing-visual')}`, [['display', 'none']]);
  add(`${spin} > svg`, [['inline-size', '100%'], ['block-size', '100%'], ['animation', `${PREFIX}-spin ${motion('motion.turn')} linear infinite`]]);
  const reduced: Rule[] = [
    { sel: `${spin} > svg`, decls: [['animation-duration', motion('motion.turn-reduced')]] },
    { sel: `${busy} > ${cls('control')} > ${cls('spinner')}`, decls: [['animation-duration', motion('motion.enter-reduced')]] },
  ];

  // ---------------------------------------------------------------- the Show/Hide button (password-field only)
  if (toggleAt) {
    const row = partSel(ROOT, 'container/labelRow');
    const variant = toggleAt.variant as Record<string, string>;
    add(row, [['display', 'flex'], ['align-items', 'flex-end']], 'the label row (Q301.2 B): the label, then the Show/Hide button at its end, one label line tall (Q380 A)');
    add(partSel(ROOT, 'container/labelRow/labelCell'), [['flex', '1 1 auto'], ['min-inline-size', '0']]);
    add(tsel(ROOT), [['flex', 'none'], ['min-block-size', '0']], 'the nested Button (Q301.3 B), small, text, flush: one line of its label, so the row takes the label\'s height (codeOnly hit-target)');
    add(`${tsel(ROOT)}[hidden]`, [['display', 'none']], 'before the script runs the button is hidden, so the field is a plain password input (Q86 A)');
    add(`${tsel(ROOT)} .${PREFIX}-password-field__toggle-suffix, .${PREFIX}-password-field__announcer`, [
      ['position', 'absolute'], ['inline-size', '1px'], ['block-size', '1px'], ['overflow', 'hidden'], ['clip-path', 'inset(50%)'], ['white-space', 'nowrap'],
    ], 'visually hidden: the " password" that completes the button\'s name, and the polite live region the script announces in');
    add(`${E}::-ms-reveal`, [['display', 'none']], 'one toggle only (codeOnly platform-owned): the browser\'s own reveal button is hidden');
    // The hit area (codeOnly hit-target, Q-HT1 A): the button def's floor at the FIELD's size. At the button's own size
    // (small) Button's centered flush rule holds; a larger floor is anchored to the row's bottom, never into the box.
    const own = hitTargetFloor(variant.size);
    for (const size of axisValues(spec, 'size')) {
      const t = hitTargetFloor(size);
      const w = v(t);
      add(`${tsel(rootSel({ size }))}::before`, t === own ? [
        ['inset-block', `min(0%, calc((100% - ${w}) / 2))`],
        ['inset-inline', `min(0%, calc((100% - ${w}) / 2))`],
      ] : [
        ['inset-block-start', `min(0%, calc(100% - ${w}))`],
        ['inset-block-end', '0'],
        ['inset-inline', `min(0%, calc((100% - ${w}) / 2))`],
      ], `hit target at ${size}: the button def's size.${size}.hit-target, ${t}${t === own ? ', centered' : ', anchored to the row\'s bottom'}`);
    }
  }
  return { css: write(`${P.def.name} (${id})`, 'specs.json, component-defs.json, generated by emit-component-docs.ts --uncommitted', rules, reduced, true), rules: rules.length + reduced.length };
};

