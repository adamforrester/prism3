/**
 * Prism3 — THE TAILWIND v4 `@theme` PROJECTOR (#2997 PR 3). Writes `tailwind/<brand>.theme.css` for every brand.
 *
 *   npx tsx packages/engine/emit-tailwind.ts                 # write out/tailwind/<brand>.theme.css
 *   npx tsx packages/engine/emit-tailwind.ts --out <dir>     # write <dir>/tailwind/** instead (what a gate renders)
 *
 * One self-contained file a Tailwind v4 project imports after `tailwindcss`: the shadcn variables in `:root` and
 * `.dark` (the same values `emit-shadcn.ts` writes, from the same handoff), the per-mode shadow variables, and an
 * `@theme inline` block that points Tailwind's names at them. `inline` makes each utility read the variable itself
 * (`bg-primary` → `var(--primary)`), so `.dark` flips it, as shadcn's own `@theme inline` does.
 *
 * Read from the emitted handoff only, like `emit-shadcn.ts`; `projections/tailwind.ts` holds no values. Gate 5
 * (`packages/tokens` `check:shadcn`) compiles a fixture against this file with the stock Tailwind CLI.
 *
 * A REGEN STEP (Q2997.5 B, #2997 PR 4): `out/tailwind/**` is committed and drift-checked like every artifact.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENGINE_VERSION } from './version.ts';
import {
  dimensionValue, fontValue, handoffBrands, OUT_DIR, readHandoff, resolveRole, shadcnModeVars, toOklchCss,
  type Handoff, type ShadcnMode,
} from './emit-shadcn.ts';
import { SHADCN_COLOR_VARS } from './projections/shadcn.ts';
import { shadowModeVar, TAILWIND_DIMENSIONS, TAILWIND_FONTS, TAILWIND_MAP_VERSION, TAILWIND_SHADOWS } from './projections/tailwind.ts';

type Layer = { color: string; offsetX: string; offsetY: string; blur: string; spread: string; inset?: boolean };

/** A DTCG shadow (one layer or several) as a CSS `box-shadow` value, its colors in `oklch()`. */
export const shadowCss = (h: Handoff, role: string, mode: ShadcnMode): string => {
  const { type, value } = resolveRole(h, role, mode);
  const layers = (Array.isArray(value) ? value : [value]) as Layer[];
  if (type !== 'shadow' || !layers.length) throw new Error(`${h.brand} ${mode}: ${role} is not a shadow (${type})`);
  return layers.map((l) => {
    const color = /^\{/.test(l.color) ? String(resolveRole(h, l.color.slice(h.root.length + 2, -1), mode).value) : l.color;
    return `${l.inset ? 'inset ' : ''}${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${toOklchCss(color)}`;
  }).join(', ');
};

export const tailwindThemeCss = (h: Handoff): string => {
  const block = (sel: string, vars: Array<[string, string]>): string =>
    `${sel} {\n${vars.map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}\n`;
  const shadows = (mode: ShadcnMode): Array<[string, string]> =>
    Object.entries(TAILWIND_SHADOWS).map(([k, role]): [string, string] => [shadowModeVar(k), shadowCss(h, role, mode)]);
  const theme: Array<[string, string]> = [
    ...Object.keys(SHADCN_COLOR_VARS).map((k): [string, string] => [`color-${k}`, `var(--${k})`]),
    ...Object.entries(TAILWIND_DIMENSIONS).map(([k, role]): [string, string] => [k, dimensionValue(h, role)]),
    ...Object.entries(TAILWIND_FONTS).map(([k, role]): [string, string] => [k, fontValue(h, k, role)]),
    ...Object.keys(TAILWIND_SHADOWS).map((k): [string, string] => [k, `var(--${shadowModeVar(k)})`]),
  ];
  return [
    `/* ${h.brand} — a Tailwind v4 theme generated by the Prism3 engine ${ENGINE_VERSION}, tailwind map ${TAILWIND_MAP_VERSION}. Do not edit: regenerate. */\n`,
    block(':root', [...shadcnModeVars(h, 'light'), ...shadows('light')]),
    block('.dark', [...shadcnModeVars(h, 'dark'), ...shadows('dark')]),
    block('@theme inline', theme),
  ].join('\n');
};

/** Writes `<out>/tailwind/<brand>.theme.css` for every brand in `handoffDir`. */
export const emitTailwind = (out = OUT_DIR, handoffDir = OUT_DIR): string[] => {
  const dir = join(out, 'tailwind');
  mkdirSync(dir, { recursive: true });
  return handoffBrands(handoffDir).map((brand) => {
    const f = join(dir, `${brand}.theme.css`);
    writeFileSync(f, tailwindThemeCss(readHandoff(brand, handoffDir)));
    return f;
  });
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--out');
  const out = i > 0 ? resolve(process.argv[i + 1] ?? '') : OUT_DIR;
  const written = emitTailwind(out);
  console.log(`✓ tailwind: ${written.length} files written to ${join(out, 'tailwind')}`);
}
