/**
 * Writes the chrome's vendored icon set, `apps/studio/src/shell/icons/tabler.ts`, and its license beside it
 * (#3083, Q813 A: the owner picked Tabler). The icons are path data in the source, not a dependency: the
 * workspace never installs `@tabler/icons`, and nothing reads it at build or run time.
 *
 *   npm pack @tabler/icons@<exact version>      (in a scratch directory, never the workspace)
 *   tar xzf tabler-icons-<version>.tgz
 *   node apps/studio/chrome/vendor-icons.mjs <scratch>/package <icon> [<icon> ...]
 *
 * Name every icon the chrome draws (the values of `GLYPHS` in `dom.ts`); the file is rewritten whole, so an
 * icon left off the list leaves the set. Each icon's path data is copied as Tabler ships it in
 * `tabler-nodes-outline.json`, less nothing: Tabler's outline icons are paths only, and the bounding-box path
 * its SVG files open with is not in that file. The version comes from the package's own `package.json`, and
 * `LICENSE` is copied byte for byte.
 *
 * It also writes `tabler-digest.json` beside this script (#3167): the version and, per icon, the sha256 of its path
 * list (`JSON.stringify` of the `d` strings, in order) as the PACKAGE ships it. `test:chrome` holds the set it parses
 * from `tabler.ts` to that digest before any glyph arm reads it, so a hand edit to `tabler.ts` fails by name: the
 * glyph arms' oracle is the file the chrome draws from, and the digest is what holds that file to Tabler. Re-vendoring
 * rewrites both together; editing either by hand is the failure the pair exists to catch.
 *
 * Node only; it never reaches a bundle.
 */
import { createHash } from 'node:crypto';
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../src/shell/icons');
const [pkgDir, ...names] = process.argv.slice(2);
if (!pkgDir || !names.length) {
  console.error('usage: node apps/studio/chrome/vendor-icons.mjs <unpacked @tabler/icons package> <icon> [<icon> ...]');
  process.exit(2);
}
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
if (pkg.name !== '@tabler/icons') { console.error(`${pkgDir} is ${pkg.name}, not @tabler/icons`); process.exit(2); }
const nodes = JSON.parse(readFileSync(join(pkgDir, 'tabler-nodes-outline.json'), 'utf8'));

const lines = [];
/** Each icon's digest, from the package's own path data (never from `tabler.ts`). The formula is restated in
 *  `test-chrome.mjs`, which reads the file's paths: two derivations, one from each side (docs/34). */
const digest = {};
for (const name of [...new Set(names)].sort()) {
  const icon = nodes[name];
  if (!icon) { console.error(`@tabler/icons@${pkg.version} has no outline icon "${name}"`); process.exit(1); }
  const ds = icon.map(([tag, attrs]) => {
    if (tag !== 'path' || Object.keys(attrs).join() !== 'd') { console.error(`"${name}" carries a <${tag}> with ${Object.keys(attrs).join(', ')}; only bare paths are vendored`); process.exit(1); }
    return attrs.d;
  });
  lines.push(`  '${name}': [${ds.map((d) => `'${d}'`).join(', ')}],`);
  digest[name] = createHash('sha256').update(JSON.stringify(ds)).digest('hex');
}

writeFileSync(join(OUT_DIR, 'tabler.ts'), `/**
 * The chrome's icons: Tabler Icons, outline set (https://tabler.io/icons), vendored as path data (#3083, Q813 A).
 * Copyright (c) Paweł Kuna, MIT License: the full text is \`LICENSE-Tabler.txt\` beside this file, and the built
 * chrome carries the notice (\`esbuild-plugin.mjs\`, [license]).
 *
 * GENERATED by \`apps/studio/chrome/vendor-icons.mjs\` from @tabler/icons@${pkg.version}. Do not edit by hand: a
 * path changed here is no longer Tabler's. \`test:chrome\` holds every drawn glyph to this set, and this set to
 * \`apps/studio/chrome/tabler-digest.json\`, taken from the package when it was vendored (#3167).
 * Every icon is drawn on Tabler's 24-unit grid; \`glyph()\` in \`dom.ts\` sets the stroke.
 */
export const TABLER_VERSION = '${pkg.version}';

export const TABLER = {
${lines.join('\n')}
} as const satisfies Record<string, readonly string[]>;

export type TablerIcon = keyof typeof TABLER;
`);
copyFileSync(join(pkgDir, 'LICENSE'), join(OUT_DIR, 'LICENSE-Tabler.txt'));
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), 'tabler-digest.json'), `${JSON.stringify({ version: pkg.version, icons: digest }, null, 2)}\n`);
console.log(`vendored ${lines.length} icons from @tabler/icons@${pkg.version} into ${OUT_DIR}`);
