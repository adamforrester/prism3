/**
 * THE POC SCORECARD (#3408): the one-page KPI table for both arms, from records, never from memory.
 *
 *   npx tsx tools/poc-scorecard/scorecard.ts record --arm arm-1 [--only <id>,<id>]   (runs the arm's measurements)
 *   npx tsx tools/poc-scorecard/scorecard.ts render [--out <file>]                   (writes the card from the records)
 *   npx tsx tools/poc-scorecard/scorecard.ts --self-test                             (the renderer, on planted records)
 *
 * A TOOL, not a gate (`tools/CLAUDE.md`): `record` and `render` answer and exit 0, whatever the measurements say. A
 * measurement that fails is a FAIL cell on the card, with its first failing line, not a failed run.
 *
 * THE RULES the card keeps, each held by the self-test:
 *   - every row the brief names shows for every arm the card names, measured or not;
 *   - a row with no record reads "not measured", never 0, and names why when the arm says;
 *   - a failed measurement reads FAIL with its first failing line, never its count;
 *   - a passing run whose summary matches none of the row's patterns reads "unparsed", never 0;
 *   - each measured cell names the commit and the time it was recorded at.
 *
 * Records land in `tools/poc-scorecard/records/<arm>/<id>.json`, uncommitted (the folder's `.gitignore`): a record is a
 * measurement of one tree, and the card cites the commit each came from.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROWS, ARMS, CARD_ARMS, type Measure } from './measures';

const HERE = import.meta.dirname ?? '';
const ROOT = resolve(HERE, '../..');
export const RECORDS = resolve(HERE, 'records');

export type Record_ = { id: string; arm: string; cmds: string[]; exit: number; value: number | null; unit: string; summary: string; commit: string; dirty: boolean; at: string; seconds: number };

const git = (...a: string[]) => spawnSync('git', a, { cwd: ROOT, encoding: 'utf8' }).stdout.trim();

/** The row's value from a passing run's output: each pattern's first group, summed; null when none matched. */
export const parse = (m: Measure, out: string): number | null => {
  let total = 0;
  let hit = false;
  for (const re of m.value) {
    const g = new RegExp(re.source, re.flags.includes('g') ? re.flags : `${re.flags}g`);
    for (const x of out.matchAll(g)) { total += Number(x[1]); hit = true; }
  }
  return hit ? total : null;
};

export const record = (arm: string, m: Measure): Record_ => {
  const t0 = Date.now();
  let out = '';
  let exit = 0;
  for (const c of [...(m.setup ?? []), ...m.cmds]) {
    const r = spawnSync(c[0], c.slice(1), { cwd: ROOT, encoding: 'utf8', env: process.env, maxBuffer: 1 << 28 });
    out += `${r.stdout ?? ''}\n${r.stderr ?? ''}\n`;
    if (r.status !== 0) { exit = r.status ?? 1; break; }
  }
  const lines = out.split('\n');
  const summary = exit
    ? (lines.find((l) => /^FAIL/.test(l)) ?? lines.filter(Boolean).slice(-1)[0] ?? `exit ${exit}`).slice(0, 300)
    : lines.filter((l) => /^OK (?!self-test)/.test(l)).join(' / ').slice(0, 600);
  return {
    id: m.id, arm, cmds: m.cmds.map((c) => c.join(' ')), exit, value: exit ? null : parse(m, out), unit: m.unit, summary,
    commit: git('rev-parse', 'HEAD'), dirty: git('status', '--porcelain', '--untracked-files=no') !== '', at: new Date().toISOString(),
    seconds: Math.round((Date.now() - t0) / 1000),
  };
};

/** One cell: what an arm's record (or its absence) says about one row. */
export const cell = (r: Record_ | undefined, pendingWhy: string | undefined): string => {
  if (!r) return pendingWhy ? `not measured: ${pendingWhy}` : 'not measured';
  const at = `${r.commit.slice(0, 8)}${r.dirty ? '+dirty' : ''}, ${r.at.slice(0, 16).replace('T', ' ')}Z`;
  if (r.exit !== 0) return `**FAIL**: ${r.summary.replace(/\|/g, '\\|')} (${at})`;
  if (r.value === null) return `unparsed: the run passed, but its summary matched no pattern (${at})`;
  return `${r.value.toLocaleString('en-US')} ${r.unit} (${at})`;
};

export const render = (records: Record<string, Record<string, Record_>>, arms = CARD_ARMS): string => {
  const out = [
    '# POC scorecard (#3408)',
    '',
    'Generated by `tools/poc-scorecard/scorecard.ts render` from the records under `tools/poc-scorecard/records/`. Each',
    'measured cell names the commit and the UTC time it was recorded at. "not measured" means no record, not zero.',
    '',
    `| KPI | Measure | ${arms.join(' | ')} |`,
    `|---|---|${arms.map(() => '---').join('|')}|`,
  ];
  for (const row of ROWS) out.push(`| ${row.kpi} | ${row.label} | ${arms.map((a) => cell(records[a]?.[row.id], ARMS[a]?.pending[row.id])).join(' | ')} |`);
  return `${out.join('\n')}\n`;
};

export const readRecords = (dir = RECORDS): Record<string, Record<string, Record_>> => {
  const out: Record<string, Record<string, Record_>> = {};
  if (!existsSync(dir)) return out;
  for (const arm of readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name)) {
    for (const f of readdirSync(resolve(dir, arm)).filter((x) => x.endsWith('.json'))) {
      const r = JSON.parse(readFileSync(resolve(dir, arm, f), 'utf8')) as Record_;
      (out[arm] ??= {})[r.id] = r;
    }
  }
  return out;
};

// ------------------------------------------------------------------------------------------------ self-test
const planted = (over: Partial<Record_>): Record_ => ({
  id: 'kpi3-axe', arm: 'arm-1', cmds: ['x'], exit: 0, value: 400, unit: 'checks', summary: 'OK axe: 400 checks.',
  commit: 'abcdef0123456789', dirty: false, at: '2026-11-20T17:00:00.000Z', seconds: 1, ...over,
});
const row = (card: string, label: string) => card.split('\n').find((l) => l.includes(`| ${label} |`)) ?? '';
export const SELF: { name: string; check: () => string | null }[] = [
  { name: 'a measured cell shows its value, unit, commit and time', check: () => {
    const r = row(render({ 'arm-1': { 'kpi3-axe': planted({}) } }), 'axe, every story, light and dark');
    return /\| 400 checks \(abcdef01, 2026-11-20 17:00Z\) \| not measured \|$/.test(r) ? null : r; } },
  { name: 'an arm with no records still shows every row, as not measured', check: () => {
    const card = render({});
    const missing = ROWS.filter((x) => !row(card, x.label).endsWith('| not measured |'));
    return missing.length ? `rows not reading "not measured" for arm 2: ${missing.map((x) => x.id).join(', ')}` : null; } },
  { name: 'a missing record names the arm\'s reason', check: () => {
    const r = row(render({}), 'Package mode: steps, time, references left to prism3');
    return r.includes('| not measured: not built yet (plan item 3, #3408) |') ? null : r; } },
  { name: 'a failed measurement reads FAIL with its line, not a count', check: () => {
    const r = row(render({ 'arm-1': { 'kpi3-axe': planted({ exit: 1, value: 400, summary: 'FAIL axe: 2 of 400 | x' }) } }), 'axe, every story, light and dark');
    return /\| \*\*FAIL\*\*: FAIL axe: 2 of 400 \\\| x \(abcdef01/.test(r) && !/\| 400 checks/.test(r) ? null : r; } },
  { name: 'a passing run that matched no pattern reads unparsed, not 0', check: () => {
    const r = row(render({ 'arm-1': { 'kpi3-axe': planted({ value: null }) } }), 'axe, every story, light and dark');
    return r.includes('| unparsed: ') ? null : r; } },
  { name: 'a dirty tree is marked on the cell', check: () => {
    const r = row(render({ 'arm-1': { 'kpi3-axe': planted({ dirty: true }) } }), 'axe, every story, light and dark');
    return r.includes('(abcdef01+dirty,') ? null : r; } },
  { name: 'parse sums every pattern and every match, and says null on none', check: () => {
    const m = ARMS['arm-1'].measures.find((x) => x.id === 'kpi2-api-parity')!;
    const out = 'OK element parity: <p3-button> has the 12 props of the button def\nOK element parity (text-field): <p3-text-field> has the 10 props\nOK element parity (password-field): <p3-password-field> has the 9 props\nOK self-test: "x"';
    const [a, b] = [parse(m, out), parse(m, 'OK something else')];
    return a === 31 && b === null ? null : `parse gave ${a} and ${b}, expected 31 and null`; } },
  { name: 'every arm 1 row is measured or names why not', check: () => {
    const arm = ARMS['arm-1'];
    const gaps = ROWS.filter((x) => !arm.measures.some((m) => m.id === x.id) && !arm.pending[x.id]);
    const stray = [...arm.measures.map((m) => m.id), ...Object.keys(arm.pending)].filter((id) => !ROWS.some((x) => x.id === id));
    return gaps.length || stray.length ? `unaccounted: ${gaps.map((x) => x.id).join(', ')}; not a row: ${stray.join(', ')}` : null; } },
];

if (process.argv[1] && resolve(process.argv[1]) === resolve(HERE, 'scorecard.ts')) {
  const arg = (n: string) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : undefined; };
  if (process.argv.includes('--self-test')) {
    let bad = 0;
    for (const t of SELF) { const why = t.check(); if (why === null) console.log(`OK self-test: ${t.name}`); else { bad++; console.error(`FAIL self-test: ${t.name}: ${why}`); } }
    process.exit(bad ? 1 : 0);
  }
  if (process.argv[2] === 'record') {
    const arm = arg('--arm') ?? 'arm-1';
    const only = arg('--only')?.split(',');
    const ms = (ARMS[arm]?.measures ?? []).filter((m) => !only || only.includes(m.id));
    if (!ms.length) { console.log(`no measurements for ${arm}${only ? ` matching ${only.join(',')}` : ''}`); process.exit(0); }
    mkdirSync(resolve(RECORDS, arm), { recursive: true });
    for (const m of ms) {
      const r = record(arm, m);
      writeFileSync(resolve(RECORDS, arm, `${m.id}.json`), `${JSON.stringify(r, null, 1)}\n`);
      console.log(`${m.id}: ${cell(r, undefined)} [${r.seconds}s]`);
    }
  } else if (process.argv[2] === 'render') {
    const card = render(readRecords());
    const out = arg('--out');
    if (out) { writeFileSync(resolve(out), card); console.log(`wrote ${out}`); } else process.stdout.write(card);
  } else {
    console.log('usage: scorecard.ts record --arm <arm> [--only <ids>] | render [--out <file>] | --self-test');
  }
}
